import test from 'node:test'
import assert from 'node:assert/strict'
import { LocalBetaStore, LOCAL_STORAGE_KEY, LOCAL_USER_ID, nextAttendanceExpiry } from '../src/features/local-demo/store.ts'
import { createLocalStorageScope, LOCAL_CACHE_PREFIX } from '../src/features/local-demo/storage.ts'

function storage() {
  const map = new Map<string, string>()
  return { getItem: (key: string) => map.get(key) ?? null, setItem: (key: string, value: string) => { map.set(key, value) }, removeItem: (key: string) => { map.delete(key) }, key: (index: number) => [...map.keys()][index] ?? null, get length() { return map.size } }
}
const now = () => new Date(2026, 10, 22, 12).getTime()

test('local fixture starts with one isolated account, varied records and persistent conversation', () => {
  const store = new LocalBetaStore(storage(), now)
  assert.equal(store.me().userId, LOCAL_USER_ID)
  assert.equal(store.data.records.length, 11)
  assert.ok(new Set(store.data.records.map(record => record.studySeconds)).size > 1)
  assert.equal(store.data.messages.length, 1)
  assert.equal(store.data.wallet.attendance + store.data.wallet.invitation, 3500)
})
test('ending and reconnecting keeps the mate conversation, while refresh preserves the active session', () => {
  const disk = storage(), store = new LocalBetaStore(disk, now)
  const first = store.start(50)
  store.reply('request-1', '안녕')
  store.heartbeat(60, 50)
  const reloaded = new LocalBetaStore(disk, now)
  assert.equal(reloaded.start(50).id, first.id)
  assert.equal(reloaded.data.active?.presentSeconds, 50)
  const report = reloaded.finish(60, 50)
  assert.equal(report.sessionId, first.id)
  assert.equal(reloaded.data.records[0]?.cameraFocus, undefined)
  assert.notEqual(reloaded.start(50).id, first.id)
  assert.ok(reloaded.data.messages.some(message => message.text === '안녕'))
})
test('voice plus advanced costs 50 from attendance first and idempotent retries never charge twice', () => {
  const disk = storage(), store = new LocalBetaStore(disk, now)
  store.start(50); store.data.wallet.attendance = 20; store.data.wallet.invitation = 100
  store.setSettings({ voice: true, advanced: true })
  store.reply('same-request', '안녕')
  assert.equal(store.data.wallet.attendance, 0)
  assert.equal(store.data.wallet.invitation, 70)
  assert.equal(store.data.wallet.usedToday, 50)
  const count = store.data.messages.length
  store.reply('same-request', '안녕')
  assert.equal(store.data.messages.length, count)
  const reloaded = new LocalBetaStore(disk, now)
  reloaded.reply('same-request', '안녕')
  assert.equal(reloaded.data.wallet.invitation, 70)
  assert.equal(reloaded.data.messages.length, count)
})
test('insufficient credits disable paid modes and continue the same basic connection', () => {
  const store = new LocalBetaStore(storage(), now)
  store.reset('exhausted'); const { id } = store.start(50)
  assert.ok(store.reply('low-credit', '안녕').content)
  assert.deepEqual(store.data.settings, { voice: false, advanced: false })
  assert.equal(store.data.wallet.usedToday, 0)
  assert.equal(store.data.active?.id, id)
  assert.equal(store.data.wallet.attendance + store.data.wallet.invitation, 0)
})
test('05:00 expires attendance, preserves invitation credits, resets daily use and grants the new attendance', () => {
  let clock = new Date(2026, 10, 22, 4, 59, 59).getTime()
  const store = new LocalBetaStore(storage(), () => clock)
  store.data.wallet.attendance = 120; store.data.wallet.usedToday = 1380
  assert.equal(nextAttendanceExpiry(clock), new Date(2026, 10, 22, 5).getTime())
  clock += 1000; store.expireAttendance()
  assert.equal(store.data.wallet.attendance, 1500)
  assert.equal(store.data.wallet.invitation, 2000)
  assert.equal(store.data.wallet.usedToday, 0)
  assert.equal(store.data.wallet.entries.filter(entry => entry.kind === 'expiration').length, 1)
  store.expireAttendance()
  assert.equal(store.data.wallet.entries.filter(entry => entry.kind === 'expiration').length, 1)
  assert.equal(nextAttendanceExpiry(clock), new Date(2026, 10, 23, 5).getTime())
})
test('invitation rejects own and duplicate codes and rewards only after a completed connection', async () => {
  const store = new LocalBetaStore(storage(), now)
  await assert.rejects(store.redeemInvitation('LOCALCAPSULE'))
  await assert.rejects(store.redeemInvitation('!'))
  await store.redeemInvitation('FRIEND123')
  assert.equal(store.data.wallet.invitation, 2000)
  await assert.rejects(store.redeemInvitation('FRIEND123'))
  store.start(50); store.finish(60, 50); store.rewardFirstConnection(); store.rewardFirstConnection()
  assert.equal(store.data.wallet.invitation, 3000)
})
test('reset clears only the mock account snapshots, preserves real credentials and does not resurrect history', () => {
  const disk = storage(), store = new LocalBetaStore(disk, now)
  const scoped = createLocalStorageScope(disk)
  scoped.setItem(`capsule-beta-cache:v1:${LOCAL_USER_ID}`, 'mock')
  scoped.setItem(`capsule-session:${LOCAL_USER_ID}:99`, 'mock')
  disk.setItem(`capsule-beta-cache:v1:${LOCAL_USER_ID}`, 'real-same-user-id')
  disk.setItem('capsule-beta-cache:v1:7', 'real-account')
  disk.setItem('user-setting', 'preserved')
  store.reset('empty')
  assert.equal(disk.getItem(`${LOCAL_CACHE_PREFIX}capsule-beta-cache:v1:${LOCAL_USER_ID}`), null)
  assert.equal(disk.getItem(`${LOCAL_CACHE_PREFIX}capsule-session:${LOCAL_USER_ID}:99`), null)
  assert.equal(disk.getItem(`capsule-beta-cache:v1:${LOCAL_USER_ID}`), 'real-same-user-id')
  assert.equal(disk.getItem('capsule-beta-cache:v1:7'), 'real-account')
  assert.equal(disk.getItem('user-setting'), 'preserved')
  assert.equal(new LocalBetaStore(disk, now).data.records.length, 0)
  assert.equal(new LocalBetaStore(disk, now).data.messages.length, 0)
})
test('inviter reward is idempotent and capped at ten completed invited friends', () => {
  const store = new LocalBetaStore(storage(), now)
  store.completeInvitedFriend('friend-3'); store.completeInvitedFriend('friend-3')
  assert.equal(store.data.invitation.invitedCount, 3)
  assert.equal(store.data.wallet.invitation, 3000)
  store.rewardFirstConnection()
  assert.equal(store.data.wallet.invitation, 3000)
  for (let n = 4; n <= 10; n++) store.completeInvitedFriend(`friend-${n}`)
  assert.equal(store.data.invitation.invitedCount, 10)
  assert.equal(store.data.invitation.rewardedCredits, 10000)
  assert.throws(() => store.completeInvitedFriend('eleventh'))
})
test('local profile and logout persist without storing passwords or a production token', () => {
  const disk = storage(), store = new LocalBetaStore(disk, now)
  store.data.details.callName = '내 호칭'; store.profile('새 닉네임'); store.logout()
  const reloaded = new LocalBetaStore(disk, now)
  assert.equal(reloaded.data.details.callName, '내 호칭')
  assert.equal(reloaded.data.nickname, '새 닉네임')
  assert.equal(reloaded.data.authenticated, false)
  assert.doesNotMatch(disk.getItem(LOCAL_STORAGE_KEY)!, /password|accessToken|refreshToken/)
})
test('unavailable or invalid storage still permits an in-memory local connection', () => {
  const disk = storage(); disk.setItem(LOCAL_STORAGE_KEY, '{bad json')
  const store = new LocalBetaStore(disk, now)
  assert.ok(store.start(50))
  const memory = new LocalBetaStore(null, now)
  memory.start(50); assert.ok(memory.reply('memory', '안녕').content)
})
test('all legacy preferences and account caches use an isolated persistent storage view', () => {
  const disk = storage(), scoped = createLocalStorageScope(disk)
  disk.setItem('real-preference', 'untouched')
  scoped.setItem('real-preference', 'local-value'); scoped.setItem('local-only', 'yes')
  assert.equal(scoped.getItem('real-preference'), 'local-value')
  assert.equal(disk.getItem('real-preference'), 'untouched')
  assert.equal(scoped.getItem(LOCAL_STORAGE_KEY), null)
  assert.equal(scoped.length, 2)
  assert.equal(createLocalStorageScope(disk).getItem('local-only'), 'yes')
  scoped.clear()
  assert.equal(scoped.length, 0)
  assert.equal(disk.getItem('real-preference'), 'untouched')
  const memory = createLocalStorageScope(null)
  memory.setItem('key', 'value'); assert.equal(memory.getItem('key'), 'value')
})
