import test from 'node:test'
import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'
import { LocalBetaStore, LOCAL_CHARACTER_ID, LOCAL_DOHYUN_CHARACTER_ID } from '../src/features/local-demo/store.ts'

test('local transport covers the real client boundary and never forwards API or external requests', async () => {
  const server = await createServer({ configFile: false, envDir: false, logLevel: 'silent',
    server: { middlewareMode: true, hmr: false, watch: null }, resolve: { alias: { '@': fileURLToPath(new URL('../src', import.meta.url)) } } })
  try {
    const { createLocalTransport } = await server.ssrLoadModule('/src/features/local-demo/transport.ts') as typeof import('../src/features/local-demo/transport.ts')
    const store = new LocalBetaStore(null), forwarded: string[] = []
    const fetch = createLocalTransport(store, async input => { forwarded.push(String(input)); return new Response('asset') }, 'http://local.test')
    const request = (path: string, body?: object) => fetch(`http://local.test/api/backend${path}`, { method: body ? 'POST' : 'GET', ...(body ? { body: JSON.stringify(body) } : {}) })
    const home = await (await request('/home')).json()
    assert.equal(home.success, true)
    // 11-25 /home: two mate cards (채린 and the server name 서진), no rooms.
    assert.equal(home.data.rooms, undefined)
    assert.deepEqual(home.data.mates.map((mate: { id: number; name: string }) => [mate.id, mate.name]), [[LOCAL_CHARACTER_ID, '채린'], [LOCAL_DOHYUN_CHARACTER_ID, '서진']])
    assert.equal(typeof home.data.todayConnectedSeconds, 'number')
    for (const old of ['/rooms/990201', '/sessions']) assert.equal((await request(old, old === '/sessions' ? { mateId: LOCAL_CHARACTER_ID } : undefined)).status, 404)
    assert.equal((await request('/connections', { mateId: 1 })).status, 404)
    const start = await request('/connections', { mateId: LOCAL_CHARACTER_ID })
    assert.equal(start.status, 201)
    const { data } = await start.json(), path = `/connections/${data.connectionId}`
    assert.equal(data.mate.id, LOCAL_CHARACTER_ID)
    assert.equal(data.mate.format, 'ALIVING2D_V2')
    assert.equal(data.mate.modelJsonUrl, '/__local-assets/chaerin-v3/model/model.json')
    assert.equal(data.mate.engineUrl, '/__local-assets/chaerin-v3/engine/engine.js')
    assert.equal(data.greeting.trigger, 'GREETING')
    assert.equal(data.settings.talkFrequency, 'SOMETIMES')
    const busy = await (await request('/connections', { mateId: LOCAL_DOHYUN_CHARACTER_ID })).json()
    assert.deepEqual([busy.code, busy.detail.connectionId], ['CONNECTION_ALREADY_IN_PROGRESS', data.connectionId])
    // Retired event types are refused like the server (400 INVALID_EVENT); PRESENT has no reaction.
    for (const type of ['FOCUS', 'BREAK', 'YAWN']) assert.equal((await request(`${path}/events`, { type, occurredAt: new Date().toISOString() })).status, 400)
    const present = await (await request(`${path}/events`, { type: 'PRESENT', occurredAt: new Date().toISOString() })).json()
    assert.equal(present.data.reaction, null)
    const event = await (await request(`${path}/events`, { type: 'RETURN', occurredAt: new Date().toISOString() })).json()
    // Faces come as the v2 Korean label (a string in 18), like the backend seed (live2d_expressions.name)
    assert.deepEqual([event.data.reaction.trigger, event.data.reaction.expression], ['RETURN', '웃음'])
    const reaction = await (await request(`${path}/events/${event.data.eventId}/reaction`, { requestId: 'event-request', tts: false })).json()
    assert.equal(reaction.data.requestId, 'event-request')
    assert.equal(reaction.data.characters[0].expression.name, '웃음')
    assert.ok(reaction.data.characters[0].content)
    const idle = await (await request(`${path}/events`, { type: 'IDLE_TALK', occurredAt: new Date().toISOString() })).json()
    assert.equal(idle.data.reaction.trigger, 'IDLE')
    // A message for a mate who is not in this connection is refused.
    assert.equal((await request(`${path}/messages`, { requestId: 'wrong-mate', characterId: LOCAL_DOHYUN_CHARACTER_ID, content: '안녕', inputType: 'TEXT', tts: false })).status, 400)
    const stream = await request(`${path}/messages/stream`, { requestId: 'message-request', characterId: LOCAL_CHARACTER_ID, content: '안녕', inputType: 'TEXT', mode: 'BASIC', tts: false })
    assert.match(stream.headers.get('content-type')!, /text\/event-stream/)
    const wire = await stream.text()
    assert.match(wire, /event: reply/)
    const done = JSON.parse(wire.split('event: done\ndata: ')[1]!.trim())
    assert.equal(done.requestId, 'message-request')
    assert.deepEqual(done.expression, { name: '웃음' })
    assert.deepEqual([done.mode, done.charged, typeof done.credits.todayRemaining], ['BASIC', 0, 'number'])
    assert.equal(done.success, undefined)
    const beat = await request(`${path}/heartbeat`, { connectedSeconds: 0, presentSeconds: 0, cameraOnSeconds: 0, pipSeconds: 0 })
    assert.equal(beat.status, 200)
    assert.equal((await beat.json()).data.minorRemainingSeconds, null)
    // 0 ≤ present ≤ cameraOn ≤ connected ≤ elapsed, pip ≤ connected; the old body is refused.
    for (const body of [{ studySeconds: 0, presentSeconds: 0 }, { connectedSeconds: 0, presentSeconds: 1, cameraOnSeconds: 0, pipSeconds: 0 }, { connectedSeconds: 3600, presentSeconds: 0, cameraOnSeconds: 0, pipSeconds: 0 }]) {
      const refused = await (await request(`${path}/heartbeat`, body)).json()
      assert.equal(refused.code, 'INVALID_CONNECTION_TIME')
    }
    assert.equal((await request(path)).status, 409, '23 while running: CONNECTION_IN_PROGRESS')
    const resume = await (await request(`${path}/resume`, {})).json()
    assert.deepEqual([resume.data.connectionId, resume.data.connectedSeconds], [data.connectionId, 0])
    const report = await (await request(`${path}/end`, { connectedSeconds: 0, presentSeconds: 0, cameraOnSeconds: 0, pipSeconds: 0, endType: 'NORMAL' })).json()
    assert.equal(report.data.connectionId, data.connectionId)
    assert.equal(report.data.mate.id, LOCAL_CHARACTER_ID)
    assert.equal(report.data.relation.stageProgress, 85)
    assert.equal((await request(path)).status, 200)
    assert.equal((await request(`${path}/resume`, {})).status, 409)
    assert.equal((await request(`${path}/end`, { connectedSeconds: 0, presentSeconds: 0, cameraOnSeconds: 0, pipSeconds: 0 })).status, 200, '22 again returns the same record')

    // 서도현 (server name 서진): his own model (the seojin bundle), reactions, reply and closing line; never 채린's.
    const second = await (await request('/connections', { mateId: LOCAL_DOHYUN_CHARACTER_ID })).json()
    assert.equal(second.data.mate.name, '서진')
    assert.equal(second.data.mate.modelJsonUrl, '/__local-assets/seojin/model/model.json')
    assert.equal(second.data.mate.engineUrl, '/__local-assets/seojin/engine/engine.js')
    const secondPath = `/connections/${second.data.connectionId}`
    const away = await (await request(`${secondPath}/events`, { type: 'AWAY', occurredAt: new Date().toISOString() })).json()
    assert.equal(away.data.reaction.intensity, 1)
    const awayLine = await (await request(`${secondPath}/events/${away.data.eventId}/reaction`, { requestId: 'dohyun-away', intensity: 1, tts: false })).json()
    assert.equal(awayLine.data.characters[0].characterId, LOCAL_DOHYUN_CHARACTER_ID)
    assert.equal(awayLine.data.characters[0].content, '어디 가냐. 금방 올 거지?')
    const answer = await (await request(`${secondPath}/messages`, { requestId: 'dohyun-message', characterId: LOCAL_DOHYUN_CHARACTER_ID, content: '이거 모르겠어', inputType: 'TEXT', tts: false })).json()
    assert.equal(answer.data.content, '잠깐 봐봐. …아, 이거네. 여기부터 다시 해.')
    const secondReport = await (await request(`${secondPath}/end`, { connectedSeconds: 0, presentSeconds: 0, cameraOnSeconds: 0, pipSeconds: 0, endType: 'AUTO_AWAY' })).json()
    assert.equal(secondReport.data.mate.id, LOCAL_DOHYUN_CHARACTER_ID)
    assert.equal(secondReport.data.endType, 'AUTO_AWAY')
    assert.equal(secondReport.data.closingLine, '다 했네. 오늘 좀 열심히 했다? 수고했어.')
    assert.equal(store.data.records[0]!.characterIds[0], String(LOCAL_DOHYUN_CHARACTER_ID))
    assert.equal(store.data.records[0]!.roomId, String(LOCAL_DOHYUN_CHARACTER_ID))
    assert.equal(store.data.records[0]!.characterName, '서도현', 'display name')

    // 29 · 30 settings, 31 detail, 32 chat room, 33 · 34 credits, 35 · 36 · 39 referrals, 37 · 38 records, 48 login mates.
    const settings = await (await fetch('http://local.test/api/backend/me/settings', { method: 'PATCH', body: JSON.stringify({ voiceVolume: 30, pipSize: 'L' }) })).json()
    assert.deepEqual([settings.data.voiceVolume, settings.data.pipSize, settings.data.talkFrequency], [30, 'L', 'SOMETIMES'])
    assert.equal((await fetch('http://local.test/api/backend/me/settings', { method: 'PATCH', body: JSON.stringify({ volume: 30 }) })).status, 400)
    assert.equal((await (await fetch('http://local.test/api/backend/me/settings', { method: 'PATCH', body: JSON.stringify({ pipSize: null }) })).json()).data.pipSize, 'M')
    const detail = await (await request(`/mates/${LOCAL_CHARACTER_ID}`)).json()
    assert.deepEqual([detail.data.id, detail.data.model.format, detail.data.hasConversation], [LOCAL_CHARACTER_ID, 'ALIVING2D_V2', true])
    const room = await (await request(`/mates/${LOCAL_CHARACTER_ID}/messages?size=1`)).json()
    assert.equal(room.data.messages.length, 1)
    assert.equal(typeof room.data.nextCursor, 'string')
    const credits = await (await request('/credits')).json()
    assert.equal(typeof credits.data.todayUsed, 'number')
    const ledger = await (await request('/credits/transactions?filter=USE')).json()
    assert.ok(ledger.data.items.every((item: { type: string }) => item.type === 'USE'))
    assert.equal((await request('/credits/transactions?filter=BAD')).status, 400)
    assert.equal((await request('/referrals/NOPE')).status, 404)
    assert.equal((await (await request('/referrals/friend1000')).json()).data.rewardOnFirstConnection, 1000)
    assert.equal((await request('/referrals', { code: 'FRIEND1000' })).status, 400, 'deviceHash is required')
    assert.equal((await request('/referrals', { code: 'FRIEND1000', deviceHash: 'a'.repeat(64) })).status, 201)
    assert.equal((await (await request('/referrals', { code: 'CAPSULE2026', deviceHash: 'a'.repeat(64) })).json()).code, 'REFERRAL_ALREADY_ENTERED')
    assert.equal((await (await request('/referrals/me')).json()).data.canEnterCode, false)
    const myMates = await (await request('/mates/me')).json()
    assert.equal(myMates.data.mates.length, 2)
    assert.equal((await request('/records')).status, 400, 'range is required')
    const year = await (await request('/records?range=YEAR')).json()
    assert.equal(year.data.buckets.length, 12)
    assert.ok(year.data.connectionCount >= 2)
    const loginMates = await (await request('/login-mates')).json()
    assert.equal(loginMates.data.mates[0].model.format, 'ALIVING2D_V2')
    assert.equal((await request('/unknown-beta-api')).status, 404)
    await assert.rejects(fetch('https://api.capsule.ai.kr/api/me'))
    await assert.rejects(fetch('http://local.test/upload', { method: 'POST' }))
    assert.deepEqual(forwarded, [])
    await fetch('http://local.test/__local-assets/chaerin/model.model3.json')
    assert.equal(forwarded.length, 1)
    store.reset('failure')
    assert.equal((await request('/home')).status, 503)
    assert.equal((await request('/home')).status, 200)
    store.reset('loading')
    const controller = new AbortController()
    const pending = fetch('http://local.test/api/backend/home', { signal: controller.signal })
    controller.abort()
    await assert.rejects(pending)
  } finally { await server.close() }
})
